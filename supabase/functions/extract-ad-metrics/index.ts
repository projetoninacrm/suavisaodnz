import "jsr:@supabase/functions-js/edge-runtime.d.ts";
import {
  generateOpenAIText,
  OpenAIError,
  parseOpenAIJSON,
} from "../_shared/openai.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers":
    "authorization, x-client-info, apikey, content-type",
};

interface ExtractedRawMetrics {
  investimento: number;
  mensagens: number;
  cliques: number;
}

Deno.serve(async (req) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const { imageBase64 } = await req.json();

    if (typeof imageBase64 !== "string" || !imageBase64) {
      return new Response(
        JSON.stringify({ error: "Image base64 is required" }),
        {
          status: 400,
          headers: { ...corsHeaders, "Content-Type": "application/json" },
        },
      );
    }

    const content = await generateOpenAIText({
      modelEnv: "OPENAI_METRICS_MODEL",
      maxOutputTokens: 800,
      schema: {
        name: "ad_metrics",
        schema: {
          type: "object",
          additionalProperties: false,
          properties: {
            investimento: { type: "number", minimum: 0 },
            mensagens: { type: "integer", minimum: 0 },
            cliques: { type: "integer", minimum: 0 },
          },
          required: ["investimento", "mensagens", "cliques"],
        },
      },
      input: [
        {
          role: "user",
          content: [
            {
              type: "input_text",
              text:
                `Analyze this marketing metrics screenshot and extract ONLY these 3 fields:

- investimento: number (investment/budget amount in BRL. Look for "Valor gasto", "Custo", "Amount spent" or similar. Remove "R$" symbol, use dot as decimal separator)
- mensagens: number (messages/leads generated. Look for "Mensagens enviadas", "Conversões", "Conversions", "Results" or similar. This is the number of leads/messages/conversions generated by the ad)
- cliques: number (link clicks. Look for "Cliques no link", "Cliques", "Link clicks" or similar)

IMPORTANT: In Google Ads screenshots, "Conversões" or "Conversions" represents the number of messages/leads (mensagens field). "Custo" represents investimento.

Return ONLY a JSON object with these 3 fields. Example:
{"investimento": 4394.00, "mensagens": 607, "cliques": 2955}

Return ONLY the JSON object, no other text.`,
            },
            {
              type: "input_image",
              image_url: imageBase64.startsWith("data:")
                ? imageBase64
                : `data:image/png;base64,${imageBase64}`,
              detail: "high",
            },
          ],
        },
      ],
    });

    console.log("Métricas de anúncio extraídas");

    // Try to parse JSON from the response
    const rawMetrics = parseOpenAIJSON<ExtractedRawMetrics>(content);
    if (
      !rawMetrics || !Number.isFinite(rawMetrics.investimento) ||
      rawMetrics.investimento < 0 ||
      !Number.isInteger(rawMetrics.mensagens) || rawMetrics.mensagens < 0 ||
      !Number.isInteger(rawMetrics.cliques) || rawMetrics.cliques < 0
    ) {
      throw new OpenAIError(
        "Não foi possível extrair métricas válidas da imagem.",
        422,
      );
    }

    return new Response(
      JSON.stringify({ success: true, rawMetrics }),
      { headers: { ...corsHeaders, "Content-Type": "application/json" } },
    );
  } catch (error) {
    console.error("Error:", error);
    return new Response(
      JSON.stringify({
        error: error instanceof Error
          ? error.message
          : "Falha ao extrair métricas.",
      }),
      {
        status: error instanceof OpenAIError ? error.status : 500,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      },
    );
  }
});
